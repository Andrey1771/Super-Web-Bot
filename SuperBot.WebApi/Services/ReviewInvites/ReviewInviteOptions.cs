namespace SuperBot.WebApi.Services.ReviewInvites;

/// <summary>
/// Настройки приглашения оставить отзыв. Секция конфигурации "ReviewInvites".
/// </summary>
public class ReviewInviteOptions
{
    /// <summary>
    /// Рассылка выключена по умолчанию. Письмо уходит живым покупателям, и включать такое
    /// молча, одним лишь деплоем, нельзя: решение должно быть принято явно.
    /// </summary>
    public bool Enabled { get; set; }

    /// <summary>
    /// Через сколько дней после выдачи ключа писать. Семь — чтобы человек успел поиграть:
    /// на следующий день после покупки честного мнения об игре ещё нет, а через месяц она
    /// уже забыта.
    /// </summary>
    public int DelayDays { get; set; } = 7;

    /// <summary>
    /// Старше скольких дней заказы не трогаем. Нужен и как здравый смысл (писать про покупку
    /// полугодовой давности — странно), и как защита при первом включении: без верхней
    /// границы первый же запуск разослал бы письма по всей истории магазина разом.
    /// </summary>
    public int MaxAgeDays { get; set; } = 30;

    /// <summary>
    /// Сколько писем отправлять за один запуск. Ограничение не про нагрузку, а про SMTP:
    /// внезапный залп с нового домена — прямая дорога в спам.
    /// </summary>
    public int BatchSize { get; set; } = 50;
}
