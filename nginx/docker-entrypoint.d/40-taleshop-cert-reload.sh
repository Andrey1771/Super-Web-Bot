#!/bin/sh
# Продакшен: раз в 6 часов перечитывает сертификат. certbot продлевает его в общем томе,
# но работающий nginx держит в памяти старый — без перезагрузки он истёк бы через 90 дней.
# Первый выпущенный сертификат подхватывается так же (или сразу: docker compose exec nginx taleshop-reload).
[ "${NGINX_SITE:-dev}" = "prod" ] || exit 0

(
    while sleep 6h; do
        taleshop-reload >/dev/null 2>&1 || echo "taleshop: не удалось перечитать сертификат" >&2
    done
# Вывод — прямо в логи контейнера: иначе фоновый цикл держал бы открытым вывод entrypoint.
) >/proc/1/fd/1 2>/proc/1/fd/2 &
