using SuperBot.Core.Entities;

namespace SuperBot.Core.Interfaces
{
    /// <summary>
    /// Отправка состоявшейся покупки во внешнюю аналитику.
    ///
    /// Почему с сервера, а не из браузера. Событие покупки — единственное, ради которого
    /// аналитика в магазине вообще нужна: без него нет ни выручки, ни конверсии, ни окупаемости
    /// рекламы. А из браузера оно теряется чаще всего: блокировщики рекламы у игровой аудитории
    /// распространены как нигде, страница «спасибо» может не открыться, вкладку закрывают сразу
    /// после оплаты. Сервер же знает о покупке всегда — он её и подтверждает.
    ///
    /// Реализация обязана быть «тихой»: любая ошибка отправки не должна мешать заказу. Деньги
    /// уже получены, ключи выданы — падать из-за счётчика недопустимо.
    /// </summary>
    public interface IPurchaseAnalytics
    {
        Task TrackPurchaseAsync(Order order, CancellationToken cancellationToken = default);

        /// <summary>
        /// Возврат денег. Без него выручка во внешней аналитике завышена на все возвраты
        /// навсегда: покупку она получила, а о том, что деньги вернулись, не узнает ниоткуда.
        ///
        /// Полный и частичный различаются намеренно. При полном достаточно номера заказа —
        /// аналитика вычтет его целиком. При частичном нужна сумма, иначе вычтется весь заказ,
        /// и отчёт станет врать в другую сторону.
        /// </summary>
        Task TrackRefundAsync(Order order, decimal refundedAmount, bool isFullRefund, CancellationToken cancellationToken = default);
    }
}
