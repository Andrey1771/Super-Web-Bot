/**
 * Короткий код обращения, выведенный из идентификатора сессии.
 *
 * У гостя нет ни email, ни идентификатора пользователя: в списке специалиста все такие
 * обращения назывались одинаково — «Guest», и отличить одно от другого можно было только
 * по тексту последней реплики. Код это снимает, не требуя ни отдельного поля в базе, ни
 * регистрации клиента: он считается из уже существующего идентификатора, поэтому одинаков
 * в админке и в виджете у самого клиента — специалист может назвать его вслух.
 *
 * Шести символов хватает: это хвост ObjectId, у соседних сессий он всегда разный. Полное
 * совпадение теоретически возможно, поэтому код — подсказка для глаза и для поиска, а не
 * ключ: адресуемся везде по-прежнему по полному идентификатору.
 */
export const SESSION_CODE_LENGTH = 6;

export function sessionCode(sessionId: string | null | undefined): string {
  const clean = (sessionId ?? "").replace(/[^0-9a-z]/gi, "");
  return clean ? clean.slice(-SESSION_CODE_LENGTH).toUpperCase() : "";
}

/** Код с решёткой — то, что видно в интерфейсе. Пустая строка, если сессии ещё нет. */
export function formatSessionCode(sessionId: string | null | undefined): string {
  const code = sessionCode(sessionId);
  return code ? `#${code}` : "";
}
